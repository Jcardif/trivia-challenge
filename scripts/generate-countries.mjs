import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const source = new URL('../rayfin/functions/src/country-names.txt', import.meta.url)
const target = new URL('../rayfin/functions/src/countryNames.generated.ts', import.meta.url)
const countries = readFileSync(source, 'utf8')
  .split(/\r?\n/)
  .map(line => line.trim())
  .filter(line => line && !line.startsWith('#'))

if (!countries.length) throw new Error('country-names.txt needs at least one country or region.')
if (countries.some(country => country.length > 80 || !/^[\x20-\x7E]+$/.test(country))) {
  throw new Error('Country names must be at most 80 characters and use only printable ASCII characters.')
}
if (new Set(countries.map(country => country.toLowerCase())).size !== countries.length) {
  throw new Error('country-names.txt contains duplicate country names.')
}

const output =
  '// Generated by scripts/generate-countries.mjs. Edit country-names.txt instead.\n' +
  `export const COUNTRIES = [\n${countries.map(country => `  ${JSON.stringify(country)},`).join('\n')}\n] as const\n`
if (!existsSync(target) || readFileSync(target, 'utf8') !== output) writeFileSync(target, output)
