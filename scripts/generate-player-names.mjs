import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const source = new URL('../rayfin/functions/src/player-name-words.txt', import.meta.url)
const target = new URL('../rayfin/functions/src/playerNameWords.generated.ts', import.meta.url)
const words = { prefixes: [], titles: [] }
let section
for (const rawLine of readFileSync(source, 'utf8').split(/\r?\n/)) {
  const line = rawLine.trim()
  if (!line || line.startsWith('#')) continue
  if (line === '[prefixes]' || line === '[titles]') {
    section = line === '[prefixes]' ? 'prefixes' : 'titles'
    continue
  }
  if (!section || line.startsWith('[')) {
    throw new Error('player-name-words.txt entries must follow [prefixes] or [titles].')
  }
  if (words[section].includes(line))
    throw new Error(`Duplicate ${section} entry in player-name-words.txt.`)
  words[section].push(line)
}
if (!words.prefixes.length || !words.titles.length) {
  throw new Error('player-name-words.txt needs at least one prefix and one title.')
}
// Reserve a space and a 32-bit collision counter inside Player.name's 96-character limit.
if (
  Math.max(...words.prefixes.map(word => word.length)) +
    Math.max(...words.titles.map(word => word.length)) +
    1 >
  85
) {
  throw new Error('The longest combined adventurer name must be at most 85 characters.')
}
const render = values =>
  `[\n${values.map(value => `  ${JSON.stringify(value)},`).join('\n')}\n] as const`
const output =
  '// Generated by scripts/generate-player-names.mjs. Edit player-name-words.txt instead.\n' +
  `export const PLAYER_NAME_PREFIXES = ${render(words.prefixes)}\n\n` +
  `export const PLAYER_NAME_TITLES = ${render(words.titles)}\n`
if (!existsSync(target) || readFileSync(target, 'utf8') !== output) writeFileSync(target, output)
